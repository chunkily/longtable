// Copies the game-icons.net icons picked in src/lib/game-icons.picks.json
// out of the @iconify-json/game-icons package and into the two lists that
// use them:
//
//   src/lib/game-icons.generated.ts            what the picker shows and the canvas draws
//   internal/store/token_icon_game_icons.go    the keys the server accepts
//
// Generated rather than imported because the package holds all four
// thousand icons in one JSON file, and importing it would put every one of
// them in the bundle every Room Member downloads. The package is a dev
// dependency only this script reads.
//
//   npm run icons                  regenerate both files from the picks
//   npm run icons -- --search wolf list the icon names containing "wolf"
//
// A name is the last part of an icon's address on game-icons.net —
// https://game-icons.net/1x1/lorc/dragon-head.html is `dragon-head`.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const require = createRequire(import.meta.url);
const web = path.resolve(import.meta.dirname, '..');
const picksPath = path.join(web, 'src/lib/game-icons.picks.json');
const tsPath = path.join(web, 'src/lib/game-icons.generated.ts');
const goPath = path.join(web, '..', 'internal/store/token_icon_game_icons.go');

const set = require('@iconify-json/game-icons/icons.json');

const searchAt = process.argv.indexOf('--search');
if (searchAt !== -1) {
	const q = (process.argv[searchAt + 1] ?? '').toLowerCase();
	const names = Object.keys(set.icons).filter((n) => n.includes(q));
	console.log(names.join('\n') || `no icon names contain "${q}"`);
	process.exit(0);
}

const picks = JSON.parse(readFileSync(picksPath, 'utf8'));
const problems = [];
const seen = new Set();
for (const [i, p] of picks.entries()) {
	const where = `pick ${i + 1} (${p.name ?? 'no name'})`;
	if (typeof p.name !== 'string' || !set.icons[p.name]) {
		problems.push(`${where}: not a game-icons name — try npm run icons -- --search <word>`);
	}
	if (seen.has(p.name)) problems.push(`${where}: picked twice`);
	seen.add(p.name);
	if (typeof p.label !== 'string' || !p.label.trim()) problems.push(`${where}: needs a label`);
	if (
		!Array.isArray(p.words) ||
		p.words.some((w) => typeof w !== 'string' || w !== w.toLowerCase())
	) {
		problems.push(`${where}: words must be a list of lower-case strings`);
	}
}
if (problems.length) {
	console.error(problems.join('\n'));
	process.exit(1);
}

const width = set.width ?? 512;
const height = set.height ?? 512;
const entries = picks.map((p) => {
	const icon = set.icons[p.name];
	return {
		key: `game-icons:${p.name}`,
		label: p.label,
		words: p.words,
		viewBox: `0 0 ${icon.width ?? width} ${icon.height ?? height}`,
		body: icon.body
	};
});

const ts = `// Generated by scripts/vendor-game-icons.mjs from game-icons.picks.json.
// Don't edit it by hand — change the picks and run \`npm run icons\`.
//
// Icons by Lorc, Delapouite and contributors, from https://game-icons.net,
// under CC BY 3.0 (https://creativecommons.org/licenses/by/3.0/).

export interface GameIcon {
\tkey: string;
\tlabel: string;
\twords: string[];
\tviewBox: string;
\t/** SVG markup inside the <svg>, drawn in currentColor. */
\tbody: string;
}

export const GAME_ICONS: GameIcon[] = ${JSON.stringify(entries, null, '\t')};
`;

const go = `// Code generated by web/scripts/vendor-game-icons.mjs; DO NOT EDIT.

package store

// gameIconKeys are the game-icons.net icons TokenIcons accepts, in the
// order the picker shows them. Change web/src/lib/game-icons.picks.json
// and run \`npm run icons\` in web/ to add one.
var gameIconKeys = []string{
${entries.map((e) => `\t${JSON.stringify(e.key)},`).join('\n')}
}
`;

writeFileSync(tsPath, ts);
writeFileSync(goPath, go);
console.log(
	`wrote ${entries.length} game-icons to ${path.relative(web, tsPath)} and the server's list`
);
